"""Ошибки слоя выгрузки (FN-36, S2-06)."""

from __future__ import annotations


class ExportError(ValueError):
    """Сохранённый результат непригоден для выгрузки.

    Поднимается, когда объект, отданный ``store.get_result``, не проходит
    ``contracts/result.schema.json`` (повреждённый/невалидный payload) или
    несёт время без явного смещения (main-prompt.md §1). Экспорт в этом
    случае отказывает явной ошибкой, а не строит из подозрительных данных
    правдоподобно выглядящий отчёт (приёмка FN-36, п.3).
    """


__all__ = ["ExportError"]
